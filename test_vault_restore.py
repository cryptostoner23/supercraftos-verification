"""Offline invariants for AES-GCM credential restore.

No live secrets are read or written: the vault key and encrypted records are
generated inside a TemporaryDirectory with notion_db_setup.ROOT patched, and only
test fixture values are used. The live process environment is saved and restored.
"""
import base64
import json
import os
import shutil
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import notion_db_setup as vault

TEST_PROVIDER = "testprovider"
TEST_ENV = "TEST_SECRET_RESTORE_ENV"
TEST_SECRET = "fixture-secret-value-0123456789"


def _make_record(provider, secret):
    return {"provider": provider, "encrypted": vault.encrypt_secret(provider, secret)}


class RestoreTests(unittest.IsolatedAsyncioTestCase):
    def setUp(self):
        self._saved_env = os.environ.copy()

    def tearDown(self):
        os.environ.clear()
        os.environ.update(self._saved_env)

    def _patch_root(self, tmp):
        patches = [
            patch.object(vault, "ROOT", Path(tmp)),
            patch.object(vault, "_provider_env_map",
                         return_value={TEST_PROVIDER: TEST_ENV}),
        ]
        for p in patches:
            p.start()
            self.addCleanup(p.stop)
        (Path(tmp) / "data" / "autonomous").mkdir(parents=True, exist_ok=True)

    def test_restores_missing_secret_into_environment(self):
        with tempfile.TemporaryDirectory() as tmp, \
                patch.object(vault, "ROOT", Path(tmp)), \
                patch.object(vault, "_provider_env_map",
                             return_value={TEST_PROVIDER: TEST_ENV}):
            (Path(tmp) / "data" / "autonomous").mkdir(parents=True)
            (Path(tmp) / "data" / "autonomous" / f"{TEST_PROVIDER}.credential.enc.json").write_text(
                json.dumps(_make_record(TEST_PROVIDER, TEST_SECRET)))
            os.environ.pop(TEST_ENV, None)
            summary = vault.restore_environment_secrets()
        self.assertEqual(os.environ.get(TEST_ENV), TEST_SECRET)
        self.assertEqual(summary, {"restored": 1, "skipped_unknown_provider": 0})
        self.assertFalse((Path(tmp) / ".env").exists())

    def test_does_not_overwrite_existing_process_value(self):
        with tempfile.TemporaryDirectory() as tmp, \
                patch.object(vault, "ROOT", Path(tmp)), \
                patch.object(vault, "_provider_env_map",
                             return_value={TEST_PROVIDER: TEST_ENV}):
            (Path(tmp) / "data" / "autonomous").mkdir(parents=True)
            (Path(tmp) / "data" / "autonomous" / f"{TEST_PROVIDER}.credential.enc.json").write_text(
                json.dumps(_make_record(TEST_PROVIDER, TEST_SECRET)))
            os.environ[TEST_ENV] = "already-set-by-operator"
            summary = vault.restore_environment_secrets()
        # Process env always wins over a persisted credential.
        self.assertEqual(os.environ.get(TEST_ENV), "already-set-by-operator")
        self.assertEqual(summary["restored"], 0)

    def test_no_vault_key_means_no_restore(self):
        with tempfile.TemporaryDirectory() as tmp, \
                patch.object(vault, "ROOT", Path(tmp)), \
                patch.object(vault, "_provider_env_map",
                             return_value={TEST_PROVIDER: TEST_ENV}):
            os.environ.pop(TEST_ENV, None)
            summary = vault.restore_environment_secrets()
        self.assertEqual(summary, {"restored": 0, "reason": "no_vault_key"})
        self.assertNotIn(TEST_ENV, os.environ)

    def test_unknown_provider_is_skipped_not_restored(self):
        with tempfile.TemporaryDirectory() as tmp, \
                patch.object(vault, "ROOT", Path(tmp)), \
                patch.object(vault, "_provider_env_map", return_value={TEST_PROVIDER: TEST_ENV}):
            (Path(tmp) / "data" / "autonomous").mkdir(parents=True)
            (Path(tmp) / "data" / "autonomous" / "unknown.credential.enc.json").write_text(
                json.dumps(_make_record("unknown", TEST_SECRET)))
            summary = vault.restore_environment_secrets()
        self.assertNotIn(TEST_ENV, os.environ)
        self.assertEqual(summary["restored"], 0)
        self.assertEqual(summary["skipped_unknown_provider"], 1)

    def test_bad_vault_key_skips_gracefully(self):
        with tempfile.TemporaryDirectory() as tmp, \
                patch.object(vault, "ROOT", Path(tmp)), \
                patch.object(vault, "_provider_env_map",
                             return_value={TEST_PROVIDER: TEST_ENV}):
            (Path(tmp) / "data" / "autonomous").mkdir(parents=True)
            (Path(tmp) / "data" / "autonomous" / f"{TEST_PROVIDER}.credential.enc.json").write_text(
                json.dumps(_make_record(TEST_PROVIDER, TEST_SECRET)))
            # Overwrite the key generated by encrypt_secret with a wrong key.
            key_file = Path(tmp) / "data" / "vault.key"
            key_file.write_bytes(os.urandom(32)); key_file.chmod(0o600)
            os.environ.pop(TEST_ENV, None)
            summary = vault.restore_environment_secrets()
        self.assertNotIn(TEST_ENV, os.environ)
        self.assertEqual(summary["restored"], 0)


if __name__ == "__main__":
    unittest.main()
